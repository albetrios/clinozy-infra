/**
 * Browser-safe clinozy-fe keys derived from backend provisioning state / `.env.<environment>`.
 *
 * clinozy-fe is a fully independent target: these are written straight into the frontend repo's own
 * `.env.<environment>` (resolved via {@link frontendRoot}) via a SURGICAL upsert — only the mapped
 * `VITE_*` keys plus the build-time Sentry identifiers (`SENTRY_ORG`, `SENTRY_PROJECT`) are written;
 * every other clinozy-fe key, comment, and blank line is preserved byte-for-byte. The Sentry *auth
 * token* is a CI-only secret and is deliberately NEVER emitted here. Mirrors the backend upsert in
 * `export-env-files.ts`.
 */
import { resolve } from 'node:path';
import { frontendRoot } from '@setup/common/paths.js';
import type { SetupConfig, SetupSecrets, SetupState } from '@setup/common/types.js';
import { upsertEnvContent } from '@setup/engine/index.js';
import { resolveEnvironmentVariables } from '@setup/envs/build-env-vars.js';
import { escapeEnvValue } from '@setup/envs/env-file-format.util.js';

/** Canonical backend key → Vite env name for clinozy-fe. All values are public (browser-safe). */
export const FRONTEND_ENV_KEY_MAPPINGS = [
  { canonical: 'SENTRY_FRONTEND_DSN', vite: 'VITE_SENTRY_DSN' },
  { canonical: 'POSTHOG_KEY', vite: 'VITE_POSTHOG_KEY' },
  { canonical: 'POSTHOG_HOST', vite: 'VITE_POSTHOG_HOST' },
  { canonical: 'STRIPE_PUBLISHABLE_KEY', vite: 'VITE_STRIPE_PUBLISHABLE_KEY' },
  { canonical: 'CAPTCHA_SITE_KEY', vite: 'VITE_TURNSTILE_SITE_KEY' },
] as const;

export type FrontendEnvCanonicalKey = (typeof FRONTEND_ENV_KEY_MAPPINGS)[number]['canonical'];

/** Header written into a brand-new clinozy-fe env file when clinozy-fe has no `.env.example`. */
export const FRONTEND_FALLBACK_HEADER =
  '# Browser-safe keys for clinozy-fe (Vite) — generated by pnpm setup:infra:export-env';

export function frontendEnvFileName(environmentName: string): string {
  return `.env.${environmentName}`;
}

/** Absolute path to clinozy-fe's `.env.<environment>`. Throws when clinozy-fe is absent. */
export function frontendEnvFilePath(environmentName: string): string {
  return resolve(frontendRoot(), frontendEnvFileName(environmentName));
}

/**
 * Fresh, non-empty clinozy-fe values to write into the target file, keyed by their env-file name.
 * Empty values are excluded so a stateless run never blanks an existing key.
 */
export function freshFrontendValues(
  environmentName: string,
  config: SetupConfig,
  secrets: SetupSecrets,
  state: SetupState,
): Record<string, string> {
  const variables = resolveEnvironmentVariables(environmentName, config, secrets, state);
  const fresh: Record<string, string> = {};
  // Browser-safe VITE_* keys (public) mapped from backend canonical keys.
  for (const { canonical, vite } of FRONTEND_ENV_KEY_MAPPINGS) {
    const value = variables[canonical] ?? '';
    if (value !== '') fresh[vite] = value;
  }
  // Non-VITE, build-time Sentry identifiers for clinozy-fe's sourcemap upload — public, sourced from
  // config (single source of truth). The SECRET half (SENTRY_AUTH_TOKEN) is a CI-only secret and is
  // deliberately NEVER emitted into the committed env file.
  if (config.providers.sentry.enabled) {
    if (config.providers.sentry.organization) {
      fresh.SENTRY_ORG = config.providers.sentry.organization;
    }
    if (config.frontend?.name) {
      fresh.SENTRY_PROJECT = config.frontend.name;
    }
  }
  return fresh;
}

/**
 * Surgically upsert the fresh VITE_/Sentry values into clinozy-fe's existing env text (`baseText` —
 * the current `.env.<environment>` on a re-run, or the `.env.example` seed / fallback header on
 * first run). Only the mapped keys change; every other line is preserved byte-for-byte.
 */
export function buildFrontendEnvContent(baseText: string, fresh: Record<string, string>): string {
  return upsertEnvContent(baseText, fresh, escapeEnvValue).text;
}
