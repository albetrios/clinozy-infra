/**
 * `setup:infra:example` — emit committable `.env.example` files (keys + comments, no
 * values) for both targets, generated from the preset catalog + the frontend key map.
 *
 * Safe by default: writes only when the target `.env.example` does not already exist;
 * pass `--force` to overwrite. `.env.example` is committable (no secrets), so it is a
 * plain write, not a 0600 secret write.
 */
import { existsSync, writeFileSync } from 'node:fs';
import * as logger from '@setup/common/logger.js';
import { frontendRootIfExists, targetPath } from '@setup/common/paths.js';
import { resolve } from 'node:path';
import { FRONTEND_ENV_KEY_MAPPINGS } from '@setup/envs/frontend-env-keys.js';
import { PRESETS, buildEnvExample } from '@setup/presets/index.js';

/** Browser-safe clinozy-fe `.env.example` (the mapped VITE_* keys). */
export function buildFrontendEnvExample(): string {
  const lines = [
    '# .env.example (clinozy-fe) — browser-safe VITE_* keys, generated by setup:infra:example.',
    '# Copy to .env.<environment> and fill in values.',
    '',
  ];
  for (const { vite } of FRONTEND_ENV_KEY_MAPPINGS) lines.push(`${vite}=`);
  lines.push('');
  return lines.join('\n');
}

function writeExample(filePath: string, content: string, force: boolean): void {
  if (existsSync(filePath) && !force) {
    logger.info(`Skipped ${filePath} — already exists (use --force to overwrite).`);
    return;
  }
  writeFileSync(filePath, content, 'utf-8');
  logger.success(`Wrote ${filePath}`);
}

/** CLI entry. Writes clinozy-be and (if present) clinozy-fe `.env.example`. */
export function runExample(options: { force?: boolean } = {}): void {
  const force = options.force ?? false;
  writeExample(targetPath('.env.example'), buildEnvExample(PRESETS), force);

  const frontendRoot = frontendRootIfExists();
  if (frontendRoot) {
    writeExample(resolve(frontendRoot, '.env.example'), buildFrontendEnvExample(), force);
  } else {
    logger.info('Frontend repo (clinozy-fe) not found — skipped its .env.example.');
  }
}
